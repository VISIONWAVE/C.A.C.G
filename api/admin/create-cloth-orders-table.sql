-- Cloth orders for the Ebenezer cloth ordering page.
-- Safe to run once (IF NOT EXISTS). Row Level Security is switched on with
-- NO public policies on purpose: nobody can read or write this table from
-- the browser. Only our server functions (using the service role key) can,
-- so customers' phone numbers are never exposed.

CREATE TABLE IF NOT EXISTS cloth_orders (
  id bigint generated by default as identity primary key,
  name text NOT NULL,
  phone text NOT NULL,
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 50),
  size text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'payment_claimed', 'paid', 'delivered', 'cancelled')),
  admin_notes text,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE cloth_orders ENABLE ROW LEVEL SECURITY;